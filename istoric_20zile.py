def extrage_date(ticker, data_start):
    try:
        clean_t = ticker.split('_')[0]
        start_dt = datetime.strptime(data_start, '%Y-%m-%d')
        end_dt = start_dt + timedelta(days=35)
        df = yf.download(clean_t, start=data_start, end=end_dt.strftime('%Y-%m-%d'), progress=False)
        if df.empty: return None
        return df.head(20)
    except: return None

